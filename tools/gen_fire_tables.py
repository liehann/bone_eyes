#!/usr/bin/env python3
"""Generate src/eye_art/fire_tables.h for the "fire" eye style.

Everything the fire renderer needs that would otherwise involve atan2/sqrt or
random numbers is precomputed here, so the firmware (C++) and the browser
simulator (JS) do pure integer maths on identical tables and render identical
pixels.
"""
import math
from pathlib import Path

Q = 121  # quadrant table size: |dx|, |dy| in 0..120


def xorshift(seed):
    x = seed
    while True:
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        yield x


def noise_texture(w=256, h=64, seed=0x5EEDF1E):
    """Tileable value noise, w angle steps x h radial steps, u8."""
    rnd = xorshift(seed)
    out = [[0.0] * w for _ in range(h)]
    # Sum of octaves of bilinear-interpolated lattice noise; periodic in both axes.
    for cells_x, cells_y, amp in ((16, 4, 0.55), (32, 8, 0.3), (64, 16, 0.15)):
        lat = [[next(rnd) / 0xFFFFFFFF for _ in range(cells_x)] for _ in range(cells_y)]
        for y in range(h):
            fy = y * cells_y / h
            y0 = int(fy)
            ty = fy - y0
            ty = ty * ty * (3 - 2 * ty)
            for x in range(w):
                fx = x * cells_x / w
                x0 = int(fx)
                tx = fx - x0
                tx = tx * tx * (3 - 2 * tx)
                a = lat[y0 % cells_y][x0 % cells_x]
                b = lat[y0 % cells_y][(x0 + 1) % cells_x]
                c = lat[(y0 + 1) % cells_y][x0 % cells_x]
                d = lat[(y0 + 1) % cells_y][(x0 + 1) % cells_x]
                out[y][x] += amp * ((a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty)
    flat = [v for r in out for v in r]
    lo, hi = min(flat), max(flat)
    return [[round(255 * (v - lo) / (hi - lo)) for v in r] for r in out]


def palette():
    """256-entry heat -> RGB565: black, ember red, orange, yellow, white-hot."""
    stops = [(0, (0, 0, 0)), (40, (40, 0, 0)), (90, (150, 10, 0)), (150, (240, 70, 0)),
             (205, (255, 170, 20)), (240, (255, 235, 120)), (255, (255, 255, 230))]
    out = []
    for i in range(256):
        for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
            if p0 <= i <= p1:
                t = (i - p0) / (p1 - p0)
                r, g, b = (round(c0[k] + (c1[k] - c0[k]) * t) for k in range(3))
                break
        out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def main():
    radius = [min(255, math.isqrt(x * x + y * y)) for y in range(Q) for x in range(Q)]
    # Angle within a quadrant, 0..63 (0 = +x axis, 63 ~ +y axis).
    angle = [min(63, int(math.atan2(y, x) / (math.pi / 2) * 64)) for y in range(Q) for x in range(Q)]
    # Flames reach further upward: per-angle length bias (angle 64 = straight up).
    up = [round(14 * math.sin(a / 256 * 2 * math.pi)) for a in range(256)]
    noise = noise_texture()
    pal = palette()

    def arr(ctype, name, vals, per_line=24):
        lines = [", ".join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
        return f"FIRE_TABLE_ATTR const {ctype} {name}[{len(vals)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"

    out = Path(__file__).resolve().parent.parent / "src" / "eye_art" / "fire_tables.h"
    out.write_text(
        "// Generated by tools/gen_fire_tables.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n"
        "// Read per pixel by the fire renderer: keep them in internal RAM on the\n"
        "// ESP32, where flash-cache misses would dominate the frame time.\n"
        "#ifdef ARDUINO\n#include <esp_attr.h>\n#define FIRE_TABLE_ATTR DRAM_ATTR\n#else\n#define FIRE_TABLE_ATTR\n#endif\n\n"
        "namespace fire_tables {\n\n"
        f"constexpr int kQuad = {Q};\nconstexpr int kNoiseW = 256, kNoiseH = 64;\n\n"
        + arr("uint8_t", "kRadius", radius)
        + arr("uint8_t", "kAngle", angle)
        + arr("int8_t", "kUpBias", up)
        + arr("uint8_t", "kNoise", [v for r in noise for v in r])
        + arr("uint16_t", "kPalette", pal, 12)
        + "\n}  // namespace fire_tables\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()

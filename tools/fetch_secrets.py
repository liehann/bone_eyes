#!/usr/bin/env python3
"""Write include/secrets.h (gitignored) from the phloots Infisical project.

Pulls WIFI_SSID and WIFI_PASSWORD. Needs a CLI session
(`infisical login --domain https://infisical.app.phloots.com`) and the LAN/VPN.
Values are never printed. Usage: tools/fetch_secrets.py [--env prod]
"""
import argparse
import json
import pathlib
import ssl
import subprocess
import urllib.parse
import urllib.request

URL = "https://infisical.app.phloots.com"
PROJECT = "f5623517-0553-4957-83ec-208aec3af3b7"  # "phloots"
KEYS = ["WIFI_SSID", "WIFI_PASSWORD"]
OUT = pathlib.Path(__file__).resolve().parent.parent / "include" / "secrets.h"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--env", default="prod")
    args = ap.parse_args()

    token = subprocess.run(["infisical", "user", "get", "token", "--plain"], check=True,
                           capture_output=True, text=True).stdout.strip()
    q = urllib.parse.urlencode({"workspaceId": PROJECT, "environment": args.env, "secretPath": "/"})
    req = urllib.request.Request(f"{URL}/api/v3/secrets/raw?{q}",
                                 headers={"Authorization": f"Bearer {token}"})
    # The instance currently serves a self-signed cert (see phloots-infisical skill).
    ctx = ssl._create_unverified_context()
    secrets = {s["secretKey"]: s["secretValue"]
               for s in json.load(urllib.request.urlopen(req, context=ctx, timeout=15))["secrets"]}
    missing = [k for k in KEYS if not secrets.get(k)]
    if missing:
        raise SystemExit(f"missing in phloots/{args.env}: {', '.join(missing)}")

    OUT.write_text("// Generated by tools/fetch_secrets.py from Infisical (phloots/"
                   f"{args.env}). Gitignored; do not commit.\n#pragma once\n" +
                   "".join(f"#define {k} {c_str(secrets[k])}\n" for k in KEYS))
    OUT.chmod(0o600)
    print(f"wrote {OUT.relative_to(OUT.parent.parent)} ({', '.join(KEYS)} from phloots/{args.env})")


if __name__ == "__main__":
    main()
